#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" -v runtime_password="$DB_APP_PASSWORD" <<'SQL'
CREATE ROLE safanoor_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT PASSWORD :'runtime_password';
GRANT CONNECT, CREATE ON DATABASE safanoor TO safanoor_app;
GRANT USAGE ON SCHEMA public TO safanoor_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO safanoor_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE,SELECT ON SEQUENCES TO safanoor_app;
SQL
